import assert from 'node:assert/strict';
import { PROPOSED_BOUNDS } from '@generalbusiness/dap-contract';
import { canonicalBytes, entryHash } from '@generalbusiness/artroom-bytes';
import { ByteUsage, capacityFull, clockOf, entryOf, judgeGenesis, reserved, validateDefinition } from './packages/derive/src/index.ts';
import { Ledger, T0, created, creation, desk, judged, keys, ticket, valid } from './packages/derive/test/fixtures.ts';

const bounds = { ...PROPOSED_BOUNDS, entryBytes: 4096 };
const childData = structuredClone(ticket);
childData.capacity = { name: 'whole-scope', version: 1 };
const childDefinition = valid(validateDefinition(childData, bounds));
const rows = [];
for (const length of [1800, 2200]) {
  const parentData = structuredClone(desk);
  parentData.items.issue.values.padding = { fixed: false, required: false, of: { type: 'text', max: 4096 } };
  const send = parentData.acts['open-issue'].sends[0].create;
  send.definition = childDefinition.digest;
  send.result.applied.push({ value: { slot: 'padding', from: { const: 'x'.repeat(length) } } });
  const parentDefinition = valid(validateDefinition(parentData, bounds));
  const parent = created(parentDefinition);
  parent.bounds = bounds;
  const requested = parent.did(keys.rita, 'open-issue', { fields: { title: 'child' } });
  const child = new Ledger(childDefinition); child.bounds = bounds;
  const born = creation(parent, requested.seq);
  const birth = judgeGenesis(child.state, childDefinition, born.asked, { clock: clockOf(child.state, T0), bounds, facts: [], prepared: [], source: born.source });
  assert.equal(birth.result, 'write');
  if (birth.result !== 'write') throw Error('birth failed');
  child.seal(birth.draft);
  assert.equal(child.state.scope()?.status, 'provisional');
  const before = reserved(child.state, childDefinition, child.last.input);
  const answer = judged(parent, child, 0);
  assert.equal(answer.result, 'write');
  if (answer.result !== 'write') throw Error('result failed');
  parent.seal(answer.draft);
  const confirm = judged(child, parent, parent.last.seq);
  assert.equal(confirm.result, 'write');
  if (confirm.result !== 'write') throw Error('confirm failed');
  const confirmed = entryOf(child.state, confirm.draft, clockOf(child.state, T0));
  const sourceBytes = canonicalBytes(parent.last).length, confirmationBytes = canonicalBytes(confirmed).length;
  const earlierSizes = [...parent.entries.slice(0,-1).map(({entry})=>canonicalBytes(entry).length), canonicalBytes(child.last).length];
  assert(earlierSizes.every(size=>size<=bounds.entryBytes));
  assert(sourceBytes<=bounds.entryBytes&&confirmationBytes<=bounds.entryBytes);
  const usage = new ByteUsage();
  usage.journal(0, entryHash(child.last), canonicalBytes(child.last).length);
  usage.retain({kind:'entry',digest:child.last.uses[0].content}, canonicalBytes(requested).length);
  usage.retain({kind:'definition',digest:childDefinition.digest}, canonicalBytes(childDefinition.declared).length);
  const usedBefore = usage.count(); assert(usedBefore.complete);
  const ceiling = usedBefore.bytes + before.bytes;
  assert.equal(capacityFull({entries:1, bytes:usedBefore.bytes, ...child.state.keyCounts()}, before, {...bounds,scopeBytes:ceiling}), null);
  child.seal(confirm.draft);
  usage.journal(1, entryHash(child.last), confirmationBytes);
  usage.retain({kind:'entry',digest:child.last.uses[0].content}, sourceBytes);
  const after = reserved(child.state, childDefinition, child.last.input), usedAfter = usage.count(); assert(usedAfter.complete);
  const refusal = capacityFull({entries:2, bytes:usedAfter.bytes, ...child.state.keyCounts()}, after, {...bounds,scopeBytes:ceiling});
  rows.push({length,entryCeiling:bounds.entryBytes,earlierSizes,sourceBytes,confirmationBytes,bothEntriesFit:true,beforeReserved:before.bytes,afterReserved:after.bytes,actualAdditionalBytes:sourceBytes+confirmationBytes,overage:usedAfter.bytes+after.bytes-ceiling,refusal});
}
console.log(JSON.stringify({head:'f254698d07598666a2e329474024a97c5f0ac8b5',boundary:'Real in-memory genesis, result and confirmation judges/folds; fixture authority; ByteUsage admission calculation; no native SQLite/provider proof',rows},null,2));
