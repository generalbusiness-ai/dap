// Only production card inputs. No fixture projection, history, host or credentials enter these resources.
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { basename } from "node:path";
import { createHash } from "node:crypto";
import { build } from "esbuild";

const here = path => fileURLToPath(new URL(path, import.meta.url));
export const MODULE = here("../src/views/generated.ts");
const kinds = ["needs-you", "work", "decision", "change"];
export async function viewPackage() {
  const bundled = await build({ entryPoints: [here("../browser/main.ts")], bundle: true, format: "iife", platform: "browser", target: "es2022", minify: true, legalComments: "none", write: false, logLevel: "silent", outfile: here("../browser-build/card.js"), metafile: true });
  const files = Object.fromEntries(bundled.outputFiles.map(file => [basename(file.path), file.text]));
  if (Object.keys(files).sort().join(",") !== "card.css,card.js") throw new Error("The card build has unexpected outputs.");
  const template = await readFile(here("../browser/index.html"), "utf8");
  const entry = '<script type="module" src="./main.ts"></script>';
  if (template.split(entry).length !== 2 || !template.includes("</head>")) throw new Error("The card entry is not the owned template.");
  const text = template.replace(entry, `<script>${files["card.js"].replace(/<\/script/gi, "<\\/script")}</script>`).replace("</head>", `<style>${files["card.css"].replace(/<\/style/gi, "<\\/style")}</style></head>`);
  const resources = kinds.map(kind => {
    const html = text.replace("<body>", `<body data-screen="${kind}">`);
    return { uri: `ui://dap/${kind}`, name: kind, description: `Compact ${kind} card. Details are read separately through app-only tools.`, text: html, digest: `sha256:${createHash("sha256").update(html).digest("hex")}`, ui: { csp: {}, permissions: {}, prefersBorder: true } };
  });
  return { resources };
}
export async function viewModule() {
  return '// GENERATED by packages/mcp/scripts/views.mjs. Do not edit.\n// Production card inputs only; no fixture histories, host or credentials.\nimport type { PresentationPackage } from "./resources.ts";\nexport const PRESENTATION: PresentationPackage = ' + JSON.stringify(await viewPackage()) + ';\n';
}
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  await writeFile(MODULE, await viewModule());
  console.log("Wrote four self-contained MCP Apps card resources.");
}
