#!/usr/bin/env node
/** Generate the byte projection from the source-only native registry.
 * --check compares without writing; missing output is a failure in check mode.
 * No generated module lies on this script's import path. */
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { canonicalize, definitionDigest } from "@generalbusiness/dap-bytes";
import { VERSIONS } from "../src/native-catalog.ts";

const args = process.argv.slice(2);
if (args.length > 1 || args.some(arg => arg !== "--check")) throw new Error("usage: pin-native-declarations.mjs [--check]");
const pins = {}, declarations = {};
for (const named of Object.keys(VERSIONS).sort()) {
  const data = VERSIONS[named].data;
  const digest = definitionDigest(data), text = canonicalize(data);
  if (Object.hasOwn(declarations, digest) && declarations[digest] !== text) throw new Error("native digest collision");
  pins[named] = digest;
  declarations[digest] = text;
}
const output = '/** Generated by scripts/pin-native-declarations.mjs. Do not edit.\n * Byte projection only; runtime validation and reviewed policy admission remain required. */\n'
  + 'export const NATIVE_DECLARATION_PINS: Readonly<Record<string, string>> = ' + JSON.stringify(pins, null, 2) + ';\n'
  + 'export const NATIVE_DECLARATION_TEXT: Readonly<Record<string, string>> = ' + JSON.stringify(declarations, null, 2) + ';\n';
const path = fileURLToPath(new URL("../src/native-declarations.generated.ts", import.meta.url));
if (args.includes("--check")) {
  if (readFileSync(path, "utf8") !== output) throw new Error("native declaration projection is stale");
} else writeFileSync(path, output);
console.log(JSON.stringify({ identities: Object.keys(pins).length, declarations: Object.keys(declarations).length, bytes: Buffer.byteLength(output), check: args.includes("--check") }));
