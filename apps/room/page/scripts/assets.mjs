// Separate room and OAuth consent bundles, in the app-owned asset module.
//
//   node scripts/assets.mjs           writes dist/index.html, dist/page.js and apps/room/page/assets.ts
//
// `pageAssets()` gives the text of that module without writing anything; the page's test `assets.test.ts` compares it with the
// committed file, so the Worker never serves a page older than its source.
import { readFile, writeFile, mkdir } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { build } from "esbuild";

const here = (path) => fileURLToPath(new URL(path, import.meta.url));
export const MODULE = here("../assets.ts");

/** Each entry owns its HTML and bundled, minified script. */
export async function pageFiles() {
  const bundle = entry => build({ entryPoints: [here(entry)], bundle: true, format: "esm", platform: "browser", target: "es2022", minify: true, legalComments: "none", write: false, logLevel: "silent" });
  const [bundled, oauth] = await Promise.all([bundle("../src/main.ts"), bundle("../src/oauth-main.ts")]);
  return { html: await readFile(here("../src/index.html"), "utf8"), js: bundled.outputFiles[0].text, oauthHtml: await readFile(here("../src/oauth.html"), "utf8"), oauthJs: oauth.outputFiles[0].text };
}

/** The app-owned module that holds the two files, as text. */
export async function pageAssets() {
  const { html, js, oauthHtml, oauthJs } = await pageFiles();
  const digest = (text) => createHash("sha256").update(text, "utf8").digest("hex");
  return [
    "// GENERATED by apps/room/page/scripts/assets.mjs (npm run build --workspace @generalbusiness/dap-page). Do not edit.",
    "// The page that the scope Worker serves at /page/ (`route.ts`): its HTML and its one script, bundled from apps/room/page/src.",
    `// sha256 of index.html ${digest(html)}`,
    `// sha256 of page.js ${digest(js)}`,
    `export const PAGE_HTML: string = ${JSON.stringify(html)};`,
    `export const PAGE_JS: string = ${JSON.stringify(js)};`,
    `// sha256 of oauth.html ${digest(oauthHtml)}`,
    `// sha256 of oauth.js ${digest(oauthJs)}`,
    `export const OAUTH_HTML: string = ${JSON.stringify(oauthHtml)};`,
    `export const OAUTH_JS: string = ${JSON.stringify(oauthJs)};`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const { html, js, oauthHtml, oauthJs } = await pageFiles();
  await mkdir(here("../dist"), { recursive: true });
  await writeFile(here("../dist/index.html"), html);
  await writeFile(here("../dist/page.js"), js);
  await writeFile(here("../dist/oauth.html"), oauthHtml);
  await writeFile(here("../dist/oauth.js"), oauthJs);
  await writeFile(MODULE, await pageAssets());
  console.log(`page.js ${js.length} bytes; wrote dist/ and ${MODULE}`);
}
