#!/usr/bin/env node
// Pin the two lane definitions and the two of the demo profile: write the
// canonical bytes of each to definitions/, and their digests to
// src/digests.ts, from the values in src/.
//
//   node apps/room/lanes/scripts/pin.mjs
//
// A person runs it when a row of a definition changes. A changed row is a new
// definition with a new digest: scopes that pinned the earlier digest keep it.
// test/definitions.test.ts fails while the files are not the ones this writes.
//
// The digest is `definitionDigest` of the bytes package: SHA-256 over the tag
// `artroom-definition-1`, a newline and the canonical JSON of the whole value.
// Node reads the TypeScript sources directly, by removing their types.
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { canonicalize, definitionDigest } from "@generalbusiness/dap-bytes";
import { change3, changeDemo3 } from "../src/change3.ts";
import { change } from "../src/change.ts";
import { changeDemo, issueDemo } from "../src/demo.ts";
import { LANE_FORMS } from "../src/digests.ts";
import { issue } from "../src/issue.ts";
import { issueEvidence4 } from "../src/issue4.ts";
import { changeEvidence4 } from "../src/change4.ts";
import { changeJ4, issueJ4 } from "../src/j4.ts";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
// This mode writes only the new profile. It cannot repin historical lanes.
if (process.argv.includes("--j4")) {
  const pinned = Object.entries({ issue: issueJ4, change: changeJ4 }).map(([name, definition]) => {
    const bytes = canonicalize(definition);
    writeFileSync(join(root, "definitions", `${name}-j4.json`), bytes);
    return { name, digest: definitionDigest(definition), size: Buffer.byteLength(bytes) };
  });
  const digest = (name) => pinned.find((p) => p.name === name).digest;
  writeFileSync(join(root, "src", "digests-j4.ts"), `/** Explicit workspace profile; generated by scripts/pin.mjs --j4. */
import type { Digest } from "@generalbusiness/dap-contract";

export const J4_DIGESTS = {
  issue: "${digest("issue")}",
  change: "${digest("change")}",
} as const satisfies Record<string, Digest>;
`);
  for (const p of pinned) console.log(`${p.name}-j4  ${p.digest}  ${p.size} canonical bytes`);
  process.exit(0);
}
const evidenceChange = changeEvidence4(definitionDigest(issueEvidence4));
const pinned = Object.entries({ "issue-evidence4": issueEvidence4, "change-evidence4": evidenceChange, issue, change, "issue-demo": issueDemo, "change-demo": changeDemo, change3, "change-demo3": changeDemo3 }).map(([name, definition]) => {
  const bytes = canonicalize(definition);
  writeFileSync(join(root, "definitions", `${name}.json`), bytes);
  return { name, digest: definitionDigest(definition), size: Buffer.byteLength(bytes) };
});

const digest = (name) => pinned.find((p) => p.name === name).digest;
writeFileSync(join(root, "src", "digests.ts"), `/**
 * The pinned digests of the two lane definitions and of the demo profile,
 * and the text they were written from. \`scripts/pin.mjs\` writes this file
 * from the values in \`issue.ts\`, \`change.ts\` and \`demo.ts\`. A digest is exact for one value: any change
 * of a row, a name or a number is a new definition with a new digest, and a
 * scope that pinned the earlier one keeps it.
 */

import type { Digest } from "@generalbusiness/dap-contract";

/** Lane forms and browser flow: the revision and the commit whose sections 3, 4 and 8.1 the rows were written from. */
export const LANE_FORMS = { revision: ${LANE_FORMS.revision}, commit: "${LANE_FORMS.commit}" } as const;

/** The definition digest of each lane definition: SHA-256 over the tag \`artroom-definition-1\`, a newline and its canonical JSON. */
export const DIGESTS = {
  issue: "${digest("issue")}",
  change: "${digest("change")}",
} as const satisfies Record<string, Digest>;

/** The definition digest of each definition of the demo profile (\`demo.ts\`): \`definitions/issue-demo.json\` and \`definitions/change-demo.json\`. */
export const DEMO_DIGESTS = {
  issue: "${digest("issue-demo")}",
  change: "${digest("change-demo")}",
} as const satisfies Record<string, Digest>;
`);
writeFileSync(join(root, "src", "digests3.ts"), `/** Manifest-list successors; generated by scripts/pin.mjs. */\nexport const MANIFEST_DIGESTS = { change: "${digest("change3")}", demo: "${digest("change-demo3")}" } as const;\n`);
writeFileSync(join(root, "src", "digests4.ts"), `/** Opt-in evidence-rule successors; generated by scripts/pin.mjs. */\nexport const EVIDENCE_DIGESTS = { issue: "${digest("issue-evidence4")}", change: "${digest("change-evidence4")}" } as const;\n`);
writeFileSync(join(root, "..", "..", "..", "packages", "platform", "src", "evidence-lane-pins.generated.ts"), `/** Exact opt-in evidence lane identities; generated by apps/room/lanes/scripts/pin.mjs. */\nexport const EVIDENCE_LANE_PINS = { issue: "${digest("issue-evidence4")}", change: "${digest("change-evidence4")}" } as const;\n`);
for (const p of pinned) console.log(`${p.name}  ${p.digest}  ${p.size} canonical bytes`);
